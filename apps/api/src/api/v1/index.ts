/** Version 1 of the REST API, mounted at /api/v1. */
export function apiV1(deps: AppDependencies, services: ApiV1Services) {
  return async (app: FastifyInstance) => {
    app.get('/health', async (_request, reply) => {
      try {
        await deps.db.execute(sql`SELECT 1`);
        return { data: { status: 'ok', database: 'ok' } };
      } catch {
        return reply.status(503).send({ data: { status: 'degraded', database: 'unavailable' } });
      }
    });
    registerMetricsRoute(app, { deps, metrics: services.metrics });
    registerAuthRoutes(app, {
      auth: services.auth,
      config: deps.config,
      rateLimiter: services.rateLimiter,
    });
    registerMfaRoutes(app, { auth: services.auth, mfa: services.mfa, config: deps.config });
    registerOrganizationRoutes(app, services);
    registerOwnershipRoutes(app, services);
    registerInvitationRoutes(app, {
      invitations: services.invitations,
      auth: services.auth,
      config: deps.config,
    });
    registerApprovalRoutes(app, services);
    registerAccountingRoutes(app, services);
    // Phase 4B-10: the revaluation user workflow (P4-52).
    registerRevaluationRoutes(app, services);
    registerReportRoutes(app, services);
    registerPartyRoutes(app, services);
    registerFileRoutes(app, services);
    registerJobRoutes(app, services);
    registerDataExchangeRoutes(app, services);
    registerTaxRoutes(app, services);
    registerSalesRoutes(app, services);
    registerCustomerRoutes(app, services);
    registerVendorRoutes(app, services);
    registerPurchasesRoutes(app, services);
    registerBillRoutes(app, services);
    registerExpenseRoutes(app, services);
    registerBankingRoutes(app, services);
    registerInventoryRoutes(app, services);
    registerInventoryCountRoutes(app, services);
    registerInventoryBundleRoutes(app, services);
    registerInventoryWarehouseRoutes(app, services);
    registerInventoryLotRoutes(app, services);
    registerBranchScopeRoutes(app, services);
    registerClassificationRoutes(app, services);
    registerDeliveryRoutes(app, services);
    registerExpensePolicyRoutes(app, services);
    registerPettyCashRoutes(app, services);
    registerClinicConsentRoutes(app, services);
    registerOrganizationGroupRoutes(app, services);
    registerInventoryLandedCostRoutes(app, services);
    registerManagementReportRoutes(app, services);
    registerModuleRoutes(app, services);
    registerAssistantRoutes(app, services);
    registerPayrollRoutes(app, services);
    registerPayrollExtraRoutes(app, services);
    registerProjectRoutes(app, services);
    registerClinicRoutes(app, services);
    registerQuoteRoutes(app, services);
    registerSalesExtraRoutes(app, services);
    registerStatementRoutes(app, {
      statements: services.statements,
      rateLimiter: services.rateLimiter,
    });
    registerPaymentRoutes(app, {
      payments: services.payments,
      rateLimiter: services.rateLimiter,
      ...(services.mockPayments ? { mockProvider: services.mockPayments } : {}),
    });
    registerFixedAssetRoutes(app, services);
    registerExpenseClaimRoutes(app, services);
    registerApiIntegrationRoutes(app, services);
    registerWebhookRoutes(app, services);
    registerPurchaseOrderRoutes(app, services);
    registerVendorCreditRoutes(app, services);
    registerVendorPaymentRoutes(app, services);
    registerVendorRefundRoutes(app, services);
    registerCustomerRefundRoutes(app, services);
    registerPaymentBatchRoutes(app, services);
    registerRemittanceRoutes(app, services);
    registerPurchasesReportRoutes(app, services);
    registerInvoiceRoutes(app, services);
    registerReceiptRoutes(app, services);
    registerCreditNoteRoutes(app, services);
    registerSalesOutputRoutes(app, services);
    registerSalesReportRoutes(app, services);
  };
}
