import { createHash, createHmac } from 'node:crypto';
import { Readable } from 'node:stream';
import type { ReadableStream as WebReadableStream } from 'node:stream/web';
import { STORAGE_KEY, type StorageObject, type StorageProvider } from './storage.js';

/**
 * S3-compatible storage provider (FP-19). Dependency-free: requests are signed with AWS
 * Signature Version 4 and sent with `fetch`, so any S3-compatible service works (AWS S3, MinIO,
 * Cloudflare R2, Backblaze B2, Wasabi). Contents are buffered once per upload so the payload hash
 * can be signed; uploads are bounded by the file service's size limit. Keys are generated by the
 * server and validated here too (never user-controlled). The access key id and secret are never
 * logged and never included in error messages.
 */

export interface S3Config {
  /** Service endpoint, e.g. `https://s3.eu-west-1.amazonaws.com` or `http://minio:9000`. */
  endpoint: string;
  region: string;
  bucket: string;
  accessKeyId: string;
  secretAccessKey: string;
  /** Path-style addressing (`endpoint/bucket/key`); required by most self-hosted services. */
  forcePathStyle: boolean;
  /** Per-request timeout. */
  timeoutMs: number;
}

export type FetchLike = (input: string, init: RequestInit) => Promise<Response>;

const EMPTY_SHA256 = createHash('sha256').update('').digest('hex');
const sha256 = (data: Buffer | string) => createHash('sha256').update(data).digest('hex');
const hmac = (key: Buffer | string, data: string) =>
  createHmac('sha256', key).update(data).digest();

/** RFC 3986 encoding as SigV4 requires (everything but unreserved characters; `/` kept for paths). */
function encode(value: string, keepSlash: boolean) {
  const encoded = encodeURIComponent(value).replace(
    /[!'()*]/g,
    (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`,
  );
  return keepSlash ? encoded.replace(/%2F/g, '/') : encoded;
}

export interface SignInput {
  method: string;
  /** Absolute path, already URI-encoded as it will be sent. */
  canonicalPath: string;
  query: ReadonlyArray<readonly [string, string]>;
  headers: Record<string, string>;
  payloadHash: string;
  region: string;
  service: string;
  accessKeyId: string;
  secretAccessKey: string;
  now: Date;
}

/** AWS Signature Version 4: returns the headers to send (including `authorization`). */
export function signRequest(input: SignInput): Record<string, string> {
  const amzDate = input.now
    .toISOString()
    .replace(/[-:]/g, '')
    .replace(/\.\d{3}/, '');
  const date = amzDate.slice(0, 8);
  const headers: Record<string, string> = {};
  for (const [name, value] of Object.entries(input.headers)) {
    headers[name.toLowerCase()] = value.trim().replace(/\s+/g, ' ');
  }
  headers['x-amz-date'] = amzDate;
  const names = Object.keys(headers).sort();
  const canonicalHeaders = names.map((n) => `${n}:${headers[n]}\n`).join('');
  const signedHeaders = names.join(';');
  const canonicalQuery = [...input.query]
    .map(([k, v]) => [encode(k, false), encode(v, false)] as const)
    .sort((a, b) => (a[0] === b[0] ? (a[1] < b[1] ? -1 : 1) : a[0] < b[0] ? -1 : 1))
    .map(([k, v]) => `${k}=${v}`)
    .join('&');
  const canonicalRequest = [
    input.method,
    input.canonicalPath,
    canonicalQuery,
    canonicalHeaders,
    signedHeaders,
    input.payloadHash,
  ].join('\n');
  const scope = `${date}/${input.region}/${input.service}/aws4_request`;
  const stringToSign = ['AWS4-HMAC-SHA256', amzDate, scope, sha256(canonicalRequest)].join('\n');
  const signingKey = hmac(
    hmac(hmac(hmac(`AWS4${input.secretAccessKey}`, date), input.region), input.service),
    'aws4_request',
  );
  const signature = createHmac('sha256', signingKey).update(stringToSign).digest('hex');
  return {
    ...headers,
    authorization: `AWS4-HMAC-SHA256 Credential=${input.accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`,
  };
}

/** The object-storage failure; carries the HTTP status, never request headers or credentials. */
export class S3Error extends Error {
  constructor(
    message: string,
    readonly status: number,
  ) {
    super(message);
    this.name = 'S3Error';
  }
}

function decodeXml(value: string) {
  return value
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');
}

export class S3StorageProvider implements StorageProvider {
  readonly name = 's3' as const;

  constructor(
    private readonly config: S3Config,
    private readonly fetchImpl: FetchLike = (url, init) => fetch(url, init),
    private readonly clock: () => Date = () => new Date(),
  ) {}

  private target(key: string | null, query: ReadonlyArray<readonly [string, string]> = []) {
    const base = new URL(this.config.endpoint);
    const objectPath = key === null ? '' : `/${encode(key, true)}`;
    let host = base.host;
    let path: string;
    if (this.config.forcePathStyle) {
      path = `${base.pathname.replace(/\/$/, '')}/${encode(this.config.bucket, false)}${objectPath}`;
    } else {
      host = `${this.config.bucket}.${base.host}`;
      path = `${base.pathname.replace(/\/$/, '')}${objectPath || '/'}`;
    }
    const search = query.length
      ? `?${[...query].map(([k, v]) => `${encode(k, false)}=${encode(v, false)}`).join('&')}`
      : '';
    return { host, path: path || '/', url: `${base.protocol}//${host}${path || '/'}${search}` };
  }

  private async send(
    method: 'GET' | 'PUT' | 'HEAD' | 'DELETE',
    key: string | null,
    options: { body?: Buffer; query?: ReadonlyArray<readonly [string, string]> } = {},
  ): Promise<Response> {
    const query = options.query ?? [];
    const { host, path, url } = this.target(key, query);
    const payloadHash = options.body ? sha256(options.body) : EMPTY_SHA256;
    const headers = signRequest({
      method,
      canonicalPath: path,
      query,
      headers: {
        host,
        'x-amz-content-sha256': payloadHash,
      },
      payloadHash,
      region: this.config.region,
      service: 's3',
      accessKeyId: this.config.accessKeyId,
      secretAccessKey: this.config.secretAccessKey,
      now: this.clock(),
    });
    // `host` is set by fetch itself (and is part of the signature).
    delete headers.host;
    return this.fetchImpl(url, {
      method,
      headers,
      ...(options.body ? { body: new Uint8Array(options.body) } : {}),
      signal: AbortSignal.timeout(this.config.timeoutMs),
    });
  }

  private fail(action: string, response: Response): never {
    // Only the status is surfaced: the response body may echo request details.
    throw new S3Error(
      `Object storage ${action} failed (HTTP ${response.status}).`,
      response.status,
    );
  }

  private check(key: string) {
    if (!STORAGE_KEY.test(key)) throw new Error('Invalid storage key');
  }

  async put(key: string, content: Readable): Promise<void> {
    this.check(key);
    const chunks: Buffer[] = [];
    for await (const chunk of content) chunks.push(Buffer.from(chunk as Uint8Array));
    const response = await this.send('PUT', key, { body: Buffer.concat(chunks) });
    if (!response.ok) this.fail('upload', response);
  }

  async get(key: string): Promise<Readable> {
    this.check(key);
    const response = await this.send('GET', key);
    if (!response.ok || !response.body) this.fail('download', response);
    return Readable.fromWeb(response.body as WebReadableStream);
  }

  async delete(key: string): Promise<void> {
    this.check(key);
    const response = await this.send('DELETE', key);
    // S3 answers 204 for a missing key; 404 is also treated as already gone.
    if (!response.ok && response.status !== 404) this.fail('delete', response);
  }

  async exists(key: string): Promise<boolean> {
    this.check(key);
    const response = await this.send('HEAD', key);
    if (response.status === 404) return false;
    if (!response.ok) this.fail('lookup', response);
    return true;
  }

  async list(prefix: string): Promise<StorageObject[]> {
    if (!/^org\/[0-9a-f-]{36}\/$/.test(prefix)) throw new Error('Invalid tenant prefix');
    const out: StorageObject[] = [];
    let token: string | null = null;
    do {
      const query: Array<readonly [string, string]> = [
        ['list-type', '2'],
        ['prefix', prefix],
        ...(token ? [['continuation-token', token] as const] : []),
      ];
      const response = await this.send('GET', null, { query });
      if (!response.ok) this.fail('listing', response);
      const xml = await response.text();
      for (const match of xml.matchAll(/<Contents>([\s\S]*?)<\/Contents>/g)) {
        const key = /<Key>([\s\S]*?)<\/Key>/.exec(match[1]!)?.[1];
        const modified = /<LastModified>([\s\S]*?)<\/LastModified>/.exec(match[1]!)?.[1];
        if (key && modified && STORAGE_KEY.test(decodeXml(key))) {
          out.push({ key: decodeXml(key), modifiedAt: new Date(modified) });
        }
      }
      token = /<IsTruncated>true<\/IsTruncated>/.test(xml)
        ? (/<NextContinuationToken>([\s\S]*?)<\/NextContinuationToken>/.exec(xml)?.[1] ?? null)
        : null;
      if (token) token = decodeXml(token);
    } while (token);
    return out;
  }
}
