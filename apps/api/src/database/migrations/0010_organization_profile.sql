CREATE TABLE organization_profiles (
  organization_id         uuid PRIMARY KEY REFERENCES organizations (id),
  legal_name              text NOT NULL CHECK (length(btrim(legal_name)) BETWEEN 1 AND 200),
  trading_name            text CHECK (trading_name IS NULL OR length(btrim(trading_name)) BETWEEN 1 AND 200),
  tin                     text CHECK (tin IS NULL OR length(btrim(tin)) BETWEEN 1 AND 50),
  gst_registered          boolean NOT NULL DEFAULT false,
  gst_registration_number text CHECK (gst_registration_number IS NULL OR length(btrim(gst_registration_number)) BETWEEN 1 AND 50),
  gst_registered_from     date,
  email                   text CHECK (email IS NULL OR length(email) BETWEEN 3 AND 254),
  phone                   text CHECK (phone IS NULL OR length(btrim(phone)) BETWEEN 1 AND 40),
  website                 text CHECK (website IS NULL OR length(btrim(website)) BETWEEN 1 AND 200),
  -- [{scheme, value}], extensible localization identifiers (Decision 17).
  identifiers             jsonb NOT NULL DEFAULT '[]' CHECK (
    jsonb_typeof(identifiers) = 'array' AND jsonb_array_length(identifiers) <= 20),
  version                 integer NOT NULL DEFAULT 1 CHECK (version >= 1),
  updated_by_user_id      uuid NOT NULL REFERENCES users (id),
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT organization_profiles_gst_number CHECK (NOT gst_registered OR gst_registration_number IS NOT NULL)
);
CREATE TRIGGER organization_profiles_touch_updated_at BEFORE UPDATE ON organization_profiles
  FOR EACH ROW EXECUTE FUNCTION app_touch_updated_at();

CREATE TABLE organization_addresses (
  organization_id uuid NOT NULL REFERENCES organization_profiles (organization_id) ON DELETE CASCADE,
  kind            text NOT NULL CHECK (kind IN ('registered', 'business')),
  line1           text NOT NULL CHECK (length(btrim(line1)) BETWEEN 1 AND 200),
  line2           text CHECK (line2 IS NULL OR length(line2) <= 200),
  city            text CHECK (city IS NULL OR length(city) <= 100),
  region          text CHECK (region IS NULL OR length(region) <= 100),
  postal_code     text CHECK (postal_code IS NULL OR length(postal_code) <= 20),
  country_code    char(2) NOT NULL REFERENCES countries (code),
  PRIMARY KEY (organization_id, kind)
);

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['organization_profiles', 'organization_addresses'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I FOR ALL USING (organization_id = app_current_organization_id()) '
      'WITH CHECK (organization_id = app_current_organization_id())',
      t || '_tenant', t);
    EXECUTE format('REVOKE ALL ON %I FROM PUBLIC', t);
  END LOOP;
END;
$$;

