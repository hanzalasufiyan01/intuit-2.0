--   * countries: controlled ISO 3166-1 alpha-2 reference data (S4-05); global, read-only to the
--     application. Inactive countries are not newly selectable (application rule).
--   * organization_profiles: one row per organization, owned by the organizations module.
--     Created only when an authorized user saves it; nothing is inferred (S4-04). TIN and
--     identifiers are free text without statutory format validation in Phase 3A (S4-06). A GST
--     registration number is required when the organization is GST-registered (S4-07). `version`
--     supports optimistic concurrency (S4-14). The logo arrives with S5 file storage (S4-03).
--   * organization_addresses: structured registered and business addresses.

