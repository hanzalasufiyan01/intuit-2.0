  code      char(2) PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
  name      text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
  is_active boolean NOT NULL DEFAULT true
);

